# Vellum deterministic engine — state rebuild / state check (spec 5.2).
# Original code (base design credited in ATTRIBUTION.md).
"""Regenerates state/_tracking-state.json and the 7-section state-card.md,
and checks the transactional invariants gate 1 relies on.

pending_capture semantics: true while any chapter has status exactly
`accepted` — i.e., the chapter transaction (LLM capture half via @kb-lead,
demolition decision, close to `final`) has not been completed for that
chapter. `state rebuild` derives it from sources on every run; `state check`
refuses a new-chapter start while it is set."""
import json
import os
import re
import sys
from datetime import datetime, timezone

from . import util
from .util import (EXIT_OK, EXIT_ERROR, EXIT_FINDINGS, SCHEMA_VERSION,
                   STATE_CARD_MAX_BYTES, atomic_write, die)

TRACKING_FILE = "state/_tracking-state.json"
CARD_FILE = "state/state-card.md"


# ---------------------------------------------------------------------------
# Source gathering
# ---------------------------------------------------------------------------

def _gather(root):
    chapters = util.list_chapters(root)
    characters = util.load_entity_dir(root, "characters")
    promises = util.load_entity_dir(root, "promises")
    questions = util.load_entity_dir(root, "questions")
    knowledge = util.load_entity_dir(root, "knowledge")
    props = util.load_entity_dir(root, "props")
    return chapters, characters, promises, questions, knowledge, props


def _clock_rows(root):
    """Parse kb/clock.md thread rows (| thread | started | position | reading | last |)."""
    path = util.project_file(root, "kb", "clock.md")
    rows = []
    if not os.path.exists(path):
        return rows
    for line in util.read_file(path).split("\n"):
        s = line.strip()
        if not s.startswith("|") or s.startswith("|--") or s.startswith("| thread"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        if len(cells) >= 5:
            rows.append({"thread": cells[0], "started": cells[1],
                         "position": cells[2], "reading": cells[3],
                         "last_chapter": cells[4]})
    return rows


def _voice_debt(root):
    p = util.project_file(root, "work", "voice-debt.json")
    open_items = 0
    if os.path.exists(p):
        try:
            with open(p, "r", encoding="utf-8-sig") as f:
                doc = json.load(f)
            open_items = sum(1 for it in doc.get("items", [])
                             if it.get("status") == "open")
        except Exception:
            open_items = 0
    return open_items


def _exemptions_digest(root):
    doc = util.load_exemptions(root)
    active, stale = [], 0
    for e in doc.get("exemptions", []):
        if e.get("status") == "active":
            active.append(e)
        elif e.get("status") == "stale":
            stale += 1
    return active, stale


