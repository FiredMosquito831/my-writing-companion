def check(root, target=None):
    tp = util.project_file(root, *TRACKING_FILE.split("/"))
    cp = util.project_file(root, *CARD_FILE.split("/"))
    if not os.path.exists(tp) or not os.path.exists(cp):
        die("state files missing - run 'python scripts/vellum state rebuild' "
            "before starting a chapter.")
    try:
        with open(tp, "r", encoding="utf-8-sig") as f:
            tracking = json.load(f)
    except Exception:
        die("state/_tracking-state.json is unparseable - run 'python scripts/"
            "vellum state rebuild' to regenerate it.")
    if tracking.get("schema_version") != SCHEMA_VERSION:
        die("state schema is outdated (schema_version %r) - run 'python "
            "scripts/vellum state rebuild'." % tracking.get("schema_version"))
    if tracking.get("card_over_cap"):
        # Advisory, not a gate failure: the card is frozen (hash-consistent),
        # but the resume artifact may lag the sources. Surface it loudly.
        sys.stderr.write(
            "vellum: state card rebuild refused since %s - the card on disk "
            "is over the %d-byte cap and frozen; it may not reflect current "
            "kb/ content. Cut prose in the ledger sources and run 'vellum "
            "state rebuild'.\n"
            % (tracking["card_over_cap"], STATE_CARD_MAX_BYTES))

    chapters = util.list_chapters(root)

    # Resolve the write target: edits to an existing chapter are that
    # chapter's own transaction (revision, or the accepted->final close-out),
    # not a new-chapter start — the transactional invariants below are scoped
    # to new-chapter starts (spec 5.2).
    target_num, target_ch = None, None
    if target:
        m = re.match(r"^chapter-0*(\d+)\.md$",
                     os.path.basename(str(target).replace("\\", "/")))
        if m:
            target_num = int(m.group(1))
            for c in chapters:
                if c["num"] == target_num:
                    target_ch = c
                    break

    # Gate 2 acceptance precondition (spec 10.1): a pivotal chapter sitting at
    # status: accepted must carry its blind-reader artifact (verdict != LOST)
    # before its transaction can close — and before the next chapter starts.
    from .export import _blind_verdict, _blind_transcript_problems
    outlines = util.outline_files(root)
    for c in chapters:
        if c["fm"].get("status") != "accepted":
            continue
        o = outlines.get(c["num"])
        if not o or o["fm"].get("pivotal") is not True:
            continue
        verdict = _blind_verdict(root, c["num"])
        if verdict is None:
            die("chapter %s is pivotal but has no blind-reader artifact - "
                "acceptance requires work/critique-reports/blind-chapter-%02d"
                ".md with verdict ENGAGED or STALLED (never LOST); spawn "
                "@blind-reader and transcribe the verdict before closing the "
                "chapter." % (c["file"], c["num"]))
        if verdict == "LOST":
            die("chapter %s is pivotal and its blind verdict is LOST - "
                "acceptance is blocked (work/critique-reports/"
                "blind-chapter-%02d.md); revise the chapter and re-run the "
                "blind read." % (c["file"], c["num"]))
        # Same provenance binding as the readiness report: the artifact must
        # cite the blind-reader subagent transcript that carries the verdict.
        problems = _blind_transcript_problems(root, c["num"])
        if problems:
            die("chapter %s blind artifact provenance: %s" % (c["file"],
                                                              problems[0]))

    # pending capture: consult the tracking file first, then re-derive from
    # sources (a hand-edit that only flipped the flag must not pass). The
    # write that closes the pending chapter's own transaction (status: final)
    # is part of that transaction, not a new-chapter start.
    pending = [c for c in chapters if c["fm"].get("status") == "accepted"]
    if (pending and target_ch is not None
            and all(c["num"] == target_num for c in pending)):
        pass  # the target write is the pending chapter's own close-out
    elif tracking.get("pending_capture") or pending:
        die("pending_capture is true - the accepted chapter's transaction is "
            "not closed (kb capture + demolition decision + status: final). "
            "Complete the close-out before starting a new chapter.")

    mism = util.hash_mismatches(root)
    if mism:
        die("state:hand-edited - %s modified outside the engine; state files "
            "are engine-written. Run 'python scripts/vellum state rebuild' "
            "to repair." % ", ".join(mism))

    # Opt-in voice-debt gate (spec 3.8 / 5.2): when voice_debt_gate is true,
    # the post-write net's open tier-1 debt blocks the loop instead of
    # accruing silently.
    cfg = util.load_config(root)
    if cfg.get("voice_debt_gate") is True:
        debt = _voice_debt(root)
        if debt:
            die("voice debt gate (kb/project-config.json voice_debt_gate: "
                "true) - %d open tier-1 item(s) in work/voice-debt.json; "
                "resolve or explicitly clear them ('vellum debt list' / "
                "'vellum debt clear <id|all>') before continuing the "
                "chapter loop." % debt)

    # No half-committed chapter: when an approved outline exists for a higher
    # chapter than the newest on disk, the newest chapter must be closed.
    # Fires on new-chapter starts only - an edit to an existing chapter file
    # is a revision, never a start (the guards pass the write target).
    approved = sorted(n for n, o in outlines.items()
                      if o["fm"].get("approved") is True)
    if target_ch is None and approved and chapters:
        newest = max(approved)
        highest = chapters[-1]
        if newest > highest["num"]:
            st = highest["fm"].get("status")
            if st not in ("accepted", "final"):
                die("chapter %s is half-committed (status: %s) - close it out "
                    "(accept, capture, final) before starting chapter %s."
                    % (highest["file"], st, newest))

    sys.stdout.write("state ok.\n")
    return EXIT_OK
