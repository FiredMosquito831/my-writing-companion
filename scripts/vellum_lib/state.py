# State card (7 fixed sections, spec 7.4)
# ---------------------------------------------------------------------------

def _chapter_line(c):
    fm = c["fm"]
    return "- ch %s — %s (status: %s, %d words, POV %s)" % (
        fm.get("number", c["num"]), fm.get("title", c["name"]),
        fm.get("status", "unknown"), c["words"], fm.get("pov", "unset"))


def _promise_line(p):
    fm = p["fm"]
    parts = ["- %s — %s" % (fm.get("id"), fm.get("status", "?"))]
    if fm.get("planted-in"):
        parts.append("planted %s" % fm["planted-in"])
    if fm.get("target-by"):
        parts.append("target-by %s" % fm["target-by"])
    return " | ".join(parts)


def _build_card(root, chapters, characters, promises, questions, knowledge,
                props, pending):
    story = util.load_story(root)
    current = chapters[-1] if chapters else None
    cfg = util.load_config(root)

    L = []
    L.append("# State Card")
    L.append("")
    L.append("Generated by `vellum state rebuild` on %s. Machine-authoritative: "
             "never hand-edit (hash-verified). Sources: kb/, manuscript frontmatter, "
             "ledgers." % datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"))
    L.append("")

    # 1. Story position
    L.append("## Story position")
    L.append("")
    if current:
        fm = current["fm"]
        L.append("Current chapter: %s — \"%s\" (status: %s, %d words, target %s)."
                 % (current["file"], fm.get("title", "?"),
                    fm.get("status", "unknown"), current["words"],
                    fm.get("word-target", cfg.get("default_word_target"))))
        L.append("POV: %s. Cast in scene: %s."
                 % (fm.get("pov", "unset"),
                    ", ".join(_as_list(fm.get("characters"))) or "none recorded"))
    else:
        L.append("No chapters on disk yet.")
    pending_thr = [r for r in _clock_rows(root)]
    if pending_thr:
        r = pending_thr[-1]
        L.append("Clock: thread %s — %s (%s) as of %s."
                 % (r["thread"], r["position"], r["reading"], r["last_chapter"]))
    L.append("")

    # 2. Open promises & questions (top N by age)
    L.append("## Open promises & questions")
    L.append("")
    open_promises = [p for p in promises
                     if p["fm"].get("status") in
                     ("planned", "planted", "reinforced")]
    open_promises.sort(key=lambda p: util.chapter_num_val(p["fm"].get("planted-in")) or 0)
    for p in open_promises[:5]:
        L.append(_promise_line(p))
    open_questions = [q for q in questions
                      if q["fm"].get("status") in ("open", "dormant")]
    open_questions.sort(key=lambda q: util.chapter_num_val(q["fm"].get("raised-in")) or 0)
    for q in open_questions[:5]:
        L.append("- %s — %s (raised %s)" % (q["fm"].get("id"),
                                            q["fm"].get("status", "?"),
                                            q["fm"].get("raised-in") or "?"))
    if not open_promises and not open_questions:
        L.append("(none open)")
    L.append("")

    # 3. Active cast state
    L.append("## Active cast state")
    L.append("")
    byid = {}
    for c in chapters:
        for cid in _as_list(c["fm"].get("characters")):
            byid.setdefault(cid, c["num"])
    live = [e for e in characters if e["fm"].get("status") != "deceased"]
    if not live:
        L.append("(no character entities recorded)")
    for e in live:
        fm = e["fm"]
        eid = fm.get("id", e["name"][:-3])
        L.append("- %s (%s) — status: %s; last in scene ch %s%s"
                 % (eid, fm.get("name", "?"), fm.get("status", "?"),
                    byid.get(eid, "?"),
                    "; POV-eligible" if fm.get("pov-eligible") else ""))
    L.append("")

    # 4. Knowledge boundaries
    L.append("## Knowledge boundaries")
    L.append("")
    found = False
    for k in knowledge:
        fm = k["fm"]
        holders = fm.get("holders") or []
        if not isinstance(holders, list):
            continue
        for h in holders:
            if isinstance(h, dict) and h.get("certainty") in ("half-glimpse", "audience-only"):
                L.append("- %s: %s holds (%s) as of %s — %s"
                         % (fm.get("id"), h.get("character"),
                            h.get("certainty"), h.get("learned-in"),
                            fm.get("title", "")))
                found = True
    if not found:
        L.append("(no restricted-certainty knowledge recorded)")
    L.append("")

    # 5. Props & clock
    L.append("## Props & clock")
    L.append("")
    for p in props:
        fm = p["fm"]
        cust = fm.get("custody") or {}
        if isinstance(cust, dict):
            L.append("- %s — owner: %s, location: %s, status: %s"
                     % (fm.get("id"), cust.get("owner") or "none",
                        cust.get("location") or "?", cust.get("status", "?")))
    for r in _clock_rows(root):
        L.append("- thread %s — %s (%s), last chapter %s"
                 % (r["thread"], r["position"], r["reading"], r["last_chapter"]))
    if not props and not _clock_rows(root):
        L.append("(no props or clock threads recorded)")
    L.append("")

    # 6. Next beats with word quotas
    L.append("## Next beats with word quotas")
    L.append("")
    outlines = util.outline_files(root)
    nxt = None
    for num in sorted(outlines):
        o = outlines[num]
        if (o["fm"].get("approved") is True
                and not any(c["num"] == num for c in chapters)):
            nxt = o
            break
    if nxt:
        L.append("Next chapter: %s (approved outline, not yet drafted)."
                 % nxt["file"])
        for line in nxt["body"].split("\n"):
            s = line.strip()
            if s and not s.startswith("#"):
                L.append("- %s" % s)
    else:
        L.append("(no approved outline awaiting a draft)")
    L.append("")

    # 7. Flags
    L.append("## Flags")
    L.append("")
    active, stale = _exemptions_digest(root)
    L.append("- Exemptions: %d active, %d stale (re-armed)."
             % (len(active), stale))
    debt = _voice_debt(root)
    L.append("- Voice debt: %d open tier-1 item(s) in work/voice-debt.json."
             % debt)
    if pending:
        L.append("- WARNING: pending_capture is true — a chapter sits at "
                 "status: accepted; complete the capture close-out before the "
                 "next chapter.")
    L.append("")
    # Optional series layer: importing it is fail-open so deleting the
    # v0.2.0 modules leaves the v0.1.1 state output byte-identical.
    try:
        from . import series_bible
        series_section = series_bible.state_card_section(root)
    except Exception:
        series_section = None
    if series_section:
        # The series card must never push the whole card over the 12KB hard
        # cap: a linked book whose own sections already fill the card would
        # otherwise freeze (card_over_cap) purely from series-driven bloat,
        # with remediation advice ("cut prose in kb/") that cannot fix it.
        # Give the injected section the remaining budget, capped at 4KB.
        # The budget must also hold the truncation marker series_bible
        # appends when the section overflows: a series section larger than
        # the marker is skipped entirely, because emitting a truncated
        # section would push the whole card over the hard cap and freeze
        # the rebuild into card_over_cap with unfixable remediation advice.
        base = "\n".join(L) + "\n"
        budget = (STATE_CARD_MAX_BYTES
                  - len(base.encode("utf-8"))
                  - len("\n".encode("utf-8")))
        max_series = min(4 * 1024, max(budget, 0))
        if max_series > 0:
            series_section = series_bible.state_card_capped_with_budget(
                series_section, max_series)
            if series_section:
                L.append(series_section)
    return "\n".join(L)


def _as_list(v):
    if v is None:
        return []
    if isinstance(v, list):
        return [x for x in v if isinstance(x, str)]
    return [str(v)]


