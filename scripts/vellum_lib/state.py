def _tracking_doc(root, chapters, pending):
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_at": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "pending_capture": pending,
        "current_chapter": (chapters[-1]["file"] if chapters else None),
        "voice_debt_open": _voice_debt(root),
        "chapters": [
            {
                "file": c["file"],
                "number": c["fm"].get("number", c["num"]),
                "status": c["fm"].get("status", "unknown"),
                "pov": c["fm"].get("pov"),
                "characters": _as_list(c["fm"].get("characters")),
                "mentions": _as_list(c["fm"].get("mentions")),
                "promises_advanced": _as_list(c["fm"].get("promises-advanced")),
                "word_target": c["fm"].get("word-target"),
                "word_count": c["fm"].get("word-count"),
            }
            for c in chapters
        ],
        "counts": {
            "chapters": len(chapters),
            "characters": 0,  # filled by callers with entity lists
            "promises": 0,
            "questions": 0,
            "knowledge": 0,
            "props": 0,
        },
    }


def rebuild(root):
    (chapters, characters, promises, questions,
     knowledge, props) = _gather(root)
    pending = any(c["fm"].get("status") == "accepted" for c in chapters)

    tracking = _tracking_doc(root, chapters, pending)
    tracking["counts"] = {
        "chapters": len(chapters),
        "characters": len(characters),
        "promises": len(promises),
        "questions": len(questions),
        "knowledge": len(knowledge),
        "props": len(props),
    }

    card = _build_card(root, chapters, characters, promises, questions,
                       knowledge, props, pending)

    release = util.lock_state(root)
    try:
        _rebuild_unlocked(root, tracking, card)
    finally:
        release()

    if tracking.get("card_over_cap"):
        sys.stdout.write(
            "state rebuilt: %d chapters, pending_capture=%s — WARNING: state "
            "card is over the %d-byte hard cap; the card on disk is frozen at "
            "its last good content (flagged in _tracking-state.json). Cut "
            "prose in the ledger sources (kb/) and rebuild.\n"
            % (len(chapters), "true" if pending else "false",
               STATE_CARD_MAX_BYTES))
    else:
        sys.stdout.write("state rebuilt: %d chapters, pending_capture=%s.\n"
                         % (len(chapters), "true" if pending else "false"))
    return EXIT_OK


_CARD_OVER_CAP_MARKER = "card rebuild refused: over cap"


def _card_with_cap(root, card):
    """Card content honoring the 12KB hard cap (spec 7.4).

    Under the cap: return (card, None). Over the cap: the rebuild cannot
    honestly regenerate the card, so the previous engine-written card is
    kept frozen (content unchanged) with a dated warning appended to its
    Flags section (the last section), and the date is returned so the
    caller can flag _tracking-state.json — the resume artifact then says
    so instead of silently serving stale content."""
    if len(card.encode("utf-8")) <= STATE_CARD_MAX_BYTES:
        return card, None
    when = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    card_path = util.project_file(root, *CARD_FILE.split("/"))
    if not os.path.exists(card_path):
        frozen = ("# State Card\n\n"
                  "## Flags\n\n"
                  "- WARNING (%s): %s (%d bytes > %d hard cap); no previous "
                  "card exists — cut prose in the ledger sources (kb/) and "
                  "run `vellum state rebuild`.\n"
                  % (when, _CARD_OVER_CAP_MARKER,
                     len(card.encode("utf-8")), STATE_CARD_MAX_BYTES))
        return frozen, when
    with open(card_path, "r", encoding="utf-8", errors="replace") as f:
        prev = f.read()
    # Strip any previous overflow warning so repeated rebuilds do not
    # accumulate warning lines.
    kept = [ln for ln in prev.split("\n")
            if _CARD_OVER_CAP_MARKER not in ln]
    frozen = "\n".join(kept).rstrip("\n") + (
        "\n- WARNING (%s): %s (%d bytes > %d hard cap); the card above is "
        "frozen at its last good content — cut prose in the ledger sources "
        "(kb/) and run `vellum state rebuild`.\n"
        % (when, _CARD_OVER_CAP_MARKER,
           len(card.encode("utf-8")), STATE_CARD_MAX_BYTES))
    return frozen, when


def _rebuild_unlocked(root, tracking, card):
    """Write the derived files + hashes WITHOUT taking the lock — for callers
    that already hold it (bible reindex must not self-deadlock).

    Card-cap overflow does not abort the rebuild: _tracking-state.json is
    still refreshed and the card is written frozen with a dated warning
    (state check, session-start, and the rebuild output surface the flag)."""
    card_out, over_since = _card_with_cap(root, card)
    tracking["card_over_cap"] = over_since
    atomic_write(util.project_file(root, *TRACKING_FILE.split("/")),
                 json.dumps(tracking, indent=2, ensure_ascii=False) + "\n")
    atomic_write(util.project_file(root, *CARD_FILE.split("/")), card_out)
    util.write_derived_hashes(root)


